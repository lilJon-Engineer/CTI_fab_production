"""Guess a starting config for a freshly uploaded reticle file.

Heuristics (everything is editable afterwards):
  - top cells: one per reticle; the one whose name mentions "gate" is the gate
    reticle, a second top cell is the S/D reticle.
  - suffix: the trailing "_xxx" of each top cell name, when the two top cells
    share the same stem ("TC_top_Gate" / "TC_top_SD").
  - layer: the layer carrying the most shapes under each top cell.
  - groups: cells named "*_top<suffix>" below the top whose children are not
    themselves "*_top" cells; groups with "PCM" in the name are split.
"""
from __future__ import annotations

from collections import Counter

import klayout.db as db

DEFAULT_TEXT_PATTERNS = ["^Letter_", "^Digit_", r"^[A-Za-z]\$\$"]
DEFAULT_SPLIT_EXCLUDE = ["^PCM_frame", "^Pad", "^Via"]


def _suffix(name: str) -> str:
    i = name.rfind("_")
    return name[i:] if i > 0 else ""


def _main_layer(ly: db.Layout, top: db.Cell) -> tuple[int, int]:
    counts = Counter()
    called = set(top.called_cells()) | {top.cell_index()}
    for li in ly.layer_indexes():
        counts[li] = sum(ly.cell(ci).shapes(li).size() for ci in called)
    li = counts.most_common(1)[0][0] if counts else None
    info = ly.get_info(li) if li is not None else db.LayerInfo(1, 0)
    return info.layer, info.datatype


def _groups(ly: db.Layout, top: db.Cell, suffix: str) -> list[str]:
    tail = "_top" + suffix
    found = []
    for ci in top.called_cells():
        c = ly.cell(ci)
        if not c.name.endswith(tail) or c.bbox().empty():
            continue
        kids = {i.cell.name for i in c.each_inst()}
        if kids and not any(k.endswith(tail) for k in kids):
            found.append(c.name[: -len(suffix)] if suffix else c.name)
    return sorted(found)


def suggest_config(path: str, defaults: dict | None = None) -> dict:
    """`defaults` (e.g. from local/defaults.toml) overrides whole sections such as
    [text], [split], [geometry], [pairing] of the suggestion."""
    ly = db.Layout()
    ly.read(path)
    tops = sorted(ly.top_cells(), key=lambda c: c.bbox().area(), reverse=True)
    if not tops:
        raise ValueError("layout has no top cell")
    gate = next((t for t in tops if "gate" in t.name.lower()), tops[0])
    others = [t for t in tops if t is not gate]
    sfx = _suffix(gate.name)
    sd = None
    if others:
        stem = gate.name[: -len(sfx)] if sfx else gate.name
        sd = next((t for t in others if t.name.startswith(stem)), others[0])
    sd_sfx = _suffix(sd.name) if sd is not None else ""
    if sd is not None and gate.name[: -len(sfx) or None] != sd.name[: -len(sd_sfx) or None]:
        sfx = sd_sfx = ""   # names do not share a stem: no suffix convention

    gl, gd = _main_layer(ly, gate)
    cfg = {
        "config_version": 1,
        "gate": {"file": "", "top_cell": gate.name, "layer": gl, "datatype": gd, "cell_suffix": sfx},
        "groups": [{"name": g, "split": "pcm" in g.lower()} for g in _groups(ly, gate, sfx)],
        "text": {"cell_patterns": DEFAULT_TEXT_PATTERNS},
        "split": {"exclude_patterns": DEFAULT_SPLIT_EXCLUDE, "own_shapes_site": True},
        "geometry": {"ignore_triangles": True, "min_finger_aspect": 5.0, "long_line_um": 100.0,
                     "dense_space_factor": 3.0},
        "pairing": {"min_coverage": 0.5},
        "resist": {"enabled": True, "drawn": "opening", "thin_um": 2.0, "min_area_um2": 0.05},
    }
    if sd is not None:
        sl, sdt = _main_layer(ly, sd)
        cfg["sd"] = {"enabled": True, "file": "", "top_cell": sd.name, "layer": sl, "datatype": sdt,
                     "cell_suffix": sd_sfx}
    for section, values in (defaults or {}).items():
        if isinstance(values, dict) and section in cfg:
            cfg[section] = {**cfg[section], **values}
    return cfg


def to_toml(cfg: dict) -> str:
    """Minimal TOML writer for the config shape above."""
    def val(v):
        if isinstance(v, bool):
            return "true" if v else "false"
        if isinstance(v, (int, float)):
            return repr(v)
        if isinstance(v, list):
            return "[\n" + "".join(f"  {val(x)},\n" for x in v) + "]"
        s = str(v)
        return f"'{s}'" if "'" not in s and "\n" not in s else '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    lines = ["# Generated by mty from the uploaded layout. Check every value.", ""]
    lines += [f"{k} = {val(v)}" for k, v in cfg.items() if not isinstance(v, (dict, list))]
    for k, v in cfg.items():
        if isinstance(v, dict):
            lines += ["", f"[{k}]"] + [f"{kk} = {val(vv)}" for kk, vv in v.items()]
    for g in cfg.get("groups", []):
        lines += ["", "[[groups]]"] + [f"{kk} = {val(vv)}" for kk, vv in g.items()]
    return "\n".join(lines) + "\n"
